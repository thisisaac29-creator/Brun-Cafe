/**
 * Utility to format numerical amounts into standard Nigerian Naira representation.
 */
export function formatNaira(amount?: number | null, fallback = "Counter Rate"): string {
  if (amount === null || amount === undefined) {
    return fallback;
  }
  return `₦${amount.toLocaleString("en-NG")}`;
}

